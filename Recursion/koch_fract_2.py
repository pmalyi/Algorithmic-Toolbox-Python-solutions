import turtle
# Підключаємо стандартний модуль turtle для малювання "черепашкою"

def drawKoch(d, n):
    """
    Рекурсивна функція для побудови кривої Коха.
    d: довжина поточного відрізка
    n: глибина рекурсії (ступінь фракталу)
    """
    if n == 0:
        # Базовий випадок: якщо глибина 0, просто малюємо прямий відрізок
        turtle.forward(d)
    else:
        # Рекурсивно малюємо першу третину кривої
        drawKoch(d/3, n-1)
        # Поворот черепашки на 60 градусів вліво для вершини трикутника
        turtle.left(60)
        # Друга третина рекурсивно
        drawKoch(d/3, n-1)
        # Поворот на 120 градусів вправо для формування "гірки" кривої
        turtle.right(120)
        # Третя третина рекурсивно
        drawKoch(d/3, n-1)
        # Поворот на 60 градусів вліво, щоб повернутися до напрямку прямої
        turtle.left(60)
        # Остання четверта третина кривої
        drawKoch(d/3, n-1)

def main():
    # Встановлюємо розміри вікна для малювання
    width = 900
    height = 700

    # Довжина сторони великої кривої
    d = 500

    # Створюємо вікно черепашки
    screen = turtle.Screen()
    screen.setup(width, height)  # Встановлюємо розмір вікна

    # Глибина рекурсії (ступінь фракталу)
    # Запит користувача: число повинно бути цілим
    n = screen.numinput("Ступінь фракталу",
                        "Введіть ступінь фракталу (0-6):",
                        minval=0, maxval=6)

    n = int(n)

    # Початкова позиція черепашки
    turtle.penup()           # Піднімаємо перо, щоб переміщення не малювало лінію
    turtle.goto(-400, 100)  # Переміщаємо черепашку у верхній лівий кут
    turtle.setheading(0)     # Напрямок черепашки вправо (0 градусів)
    turtle.pendown()         # Опускаємо перо, щоб почати малювати
    turtle.speed(2)  # максимальна швидкість

    # Малюємо сніжинку Коха (трикутник із трьох кривих Коха)

    drawKoch(d, n)      # Малюємо одну сторону
           # Поворот на 120 градусів, щоб намалювати наступну сторону

    # Приховуємо черепашку після завершення малювання
    turtle.hideturtle()
    # Завершуємо малювання та чекаємо закриття вікна користувачем
    turtle.done()

# Виклик main() при запуску скрипта напряму
if __name__ == "__main__":
    main()
