# використаємо алгоритм бінарного пошуку для знаходження позиції вставки елемента в відсортований масив
# це дозволить нам ефективно будувати найтривалішу зростаючу підпослідовність
# time complexity: O(n log n)
# space complexity: O(n)

# знаходить позицію у невідсортованому масиві, де можна вставити елемент так, щоб зберегти порядок
def binary_search(arr, target):
    left, right = 0, len(arr) - 1
    while left <= right:
        mid = left + (right - left) // 2
        if arr[mid] < target:
            left = mid + 1
        else:
            right = mid - 1
    return left

def longest_increasing_subsequence(arr):
    if not arr:
        return []

    n = len(arr)
    tails = [] # зберігає найменший кінець для всіх зростаючих підпослідовностей з різною довжиною
    parent = [-1] * n # зберігає індекс попереднього елемента в підпослідовності для відновлення послідовності

    for i in range(n):
        pos = binary_search(tails, arr[i]) # знайти позицію для вставки arr[i] в tails
        
        if pos < len(tails): # якщо позиція знаходиться в межах поточного розміру tails, замінити елемент на цій позиції
            tails[pos] = arr[i] 
        else: # інакше додати arr[i] в кінець tails
            tails.append(arr[i])
        
        if pos > 0: # якщо pos > 0, оновити parent для поточного індексу
            parent[i] = tails[pos - 1]

    # Відновлення послідовності
    lis_length = len(tails)
    # LIS найдовша зростаюча підпослідовність
    lis_sequence = []
    current_value = tails[-1]

    for i in range(n - 1, -1, -1):
        if arr[i] == current_value:
            lis_sequence.append(arr[i])
            current_value = parent[i]

    return lis_length, lis_sequence[::-1]

def main():
    test_cases = int(input().strip())
    input() # пропускаємо порожній рядок
    for _ in range(test_cases):
        heights = []
        while True:
            try:
                line = input().strip()
                if line == "":
                    break
                heights.append(int(line))
            except EOFError:
                break
        
        max_hits, sequence = longest_increasing_subsequence(heights)
        print(f"Max hits: {max_hits}")
        for height in sequence:
            print(height)
