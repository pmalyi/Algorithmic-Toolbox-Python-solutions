'''
https://eolymp.com/uk/problems/10418
Фермер Джон відкрив басейн для своїх корів, сподіваючись, що це допоможе їм розслабитися і виробляти більше молока.

З метою безпеки він наймає n корів як рятувальників, кожна з яких має зміну, що охоплює певний безперервний проміжок 
часу протягом дня. Для простоти, басейн відкритий з часу t=0 до t=1000 щодня, тому кожну зміну можна описати двома цілими 
числами, які визначають час початку і закінчення зміни корови. Наприклад, рятувальник, що починає в момент часу t=4 і 
закінчує в момент часу t=7, охоплює три одиниці часу (зверніть увагу, що кінцеві точки — це "точки" в часі).

На жаль, фермер Джон найняв на 1 рятувальника більше, ніж може собі дозволити. Враховуючи, що він повинен звільнити рівно 
одного рятувальника, яка максимальна кількість часу, яку ще можна покрити змінами решти рятувальників? Проміжок часу 
вважається покритим, якщо присутній хоча б один рятувальник.
'''

def solve_optimized():
    
    n = int(input()) # кількість рятувальників
    shifts = []
    events = []
    
    for i in range(n):
        start, end = map(int, input().split())
        shifts.append((start, end)) # зберігаємо зміни рятувальників (час початку, час закінчення)
        events.append((start, 1, i))  # Час, тип (початок), ID корови
        events.append((end, -1, i)) # Час, тип (кінець), ID корови
    
    # Сортуємо події за часом
    events.sort()
    
    total_covered = 0 # загальний час, покритий рятувальниками
    alone_time = [0] * n # час, коли кожна корова була єдиним рятувальником
    active_cows = set() # поточні активні рятувальники
    last_time = events[0][0] # час останньої обробленої події
    
    for t, type, cow_id in events:
        duration = t - last_time # тривалість з останньої події до поточної
        
        if len(active_cows) > 0: # якщо є активні рятувальники, то цей проміжок часу покритий
            total_covered += duration # додаємо тривалість до загального покриття
            
        if len(active_cows) == 1: # якщо лише одна корова була в басейні в цей проміжок
            # Тільки одна корова була в басейні в цей проміжок
            only_cow = list(active_cows)[0] # отримуємо ID цієї корови
            alone_time[only_cow] += duration # додаємо тривалість до її "унікального" часу
            
        if type == 1: # початок зміни
            active_cows.add(cow_id) # додаємо корову до активних
        else:
            active_cows.remove(cow_id) # видаляємо корову з активних
            
        last_time = t # оновлюємо час останньої обробленої події
        
    # Віднімаємо мінімальний "унікальний" час однієї корови від загального покриття
    print(total_covered - min(alone_time))

solve_optimized()