'''
https://eolymp.com/uk/problems/10268
Різдвяний експрес — потяг, що може доставити будь-кого по кільцевому метро Північного полюса. 
Кільцеве метро містить n станцій, пронумерованих цілими числами від 1 до n. 
Експрес зупинятиметься на станціях з номерами 1,2,…,n,1,2,…,n,1,2,…, і так далі...

Опираючись на статистику останніх двох років, Дідусик Морозик визначив, що кожного разу, коли потяг зупинятиметься 
на станції з номером i для кожного j (j != i) від 1 до n у потяг сядуть a[i][j] ельфів, які вийдуть на станції з номером j. 
У Дідусика Морозика важливе запитання — яка мінімально можлива кількість місць може бути у потязі, щоб задовольнити потреби 
жителів полюсу?

Ви можете вважати, що при зупинці на будь-якій станції пасажири спочатку виходять з потяга, а лише потім інші пасажири 
заходять до нього. Звісно, допомагати Морозику доведеться Вам.
'''

def solve():
        
    n = int(input()) # кількість станцій

    matrix_values = [] # зберігаємо значення a[i][j] у вигляді одного списку для оптимізації доступу до даних
    for _ in range(n):
        row = list(map(int, input().split())) # зчитуємо рядок матриці та перетворюємо його на список цілих чисел
        matrix_values.append(row) 
    
    # Використовуємо різницевий масив для обчислення навантаження на перегонах.
    # diff[i] відповідає перегону між станцією (i+1) та (i+2).
    diff = [0] * (n + 1)

    for i in range(n):
        for j in range(n):
            count = matrix_values[i][j]
            if count == 0 or i == j: # Якщо немає пасажирів або це та сама станція, пропускаємо
                continue
            
            # Якщо пасажир їде від i до j:
            if i < j:
                # Маршрут не перетинає межу n -> 1
                # Він займає перегони [i, i+1, ..., j-1]
                diff[i] += count # Пасажири сідають на станції i, тому додаємо їх до навантаження, починаючи з перегону після i
                diff[j] -= count # Пасажири виходять на станції j, тому зменшуємо навантаження, починаючи з перегону після j-1
            else:
                # Маршрут проходить через "фінішну пряму" кільця
                # Займає перегони [i, ..., n-1] та [0, ..., j-1]
                diff[i] += count # Пасажири сідають на станції i, тому додаємо їх до навантаження, починаючи з перегону після i
                diff[n] -= count # Технічна межа масиву
                diff[0] += count # Пасажири сідають на станції i, тому додаємо їх до навантаження, починаючи з перегону після i
                diff[j] -= count # Пасажири виходять на станції j, тому зменшуємо навантаження, починаючи з перегону після j-1

    # Обчислюємо префіксні суми, щоб знайти навантаження на кожному сегменті
    max_load = 0 # змінна для збереження максимального навантаження
    current_load = 0 # змінна для поточного навантаження на сегменті
    for k in range(n):
        current_load += diff[k] # оновлюємо поточне навантаження, додаючи різницю для цього сегмента
        if current_load > max_load: # оновлюємо максимальне навантаження, якщо поточне перевищує його
            max_load = current_load
            
    print(max_load) # виводимо максимальне навантаження, яке є мінімальною кількістю місць у потязі
if __name__ == "__main__":
    solve()