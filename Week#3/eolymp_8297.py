# https://eolymp.com/uk/problems/8297
'''
Маючи декілька сірників та використавши для зображення цифр відповідний шаблон, можна 
отримати різні натуральні багатоцифрові числа. Яке найменше і найбільше число можна 
скласти з K сірників, використавши їх всі?
'''

import math

def solve():
    
    k = int(input())

    # --- НАЙБІЛЬШЕ ЧИСЛО ---
    # Жадібна стратегія. Щоб отримати найбільше число, потрібно використовувати якомога 
    # більше одиниць (1), оскільки вони займають 2 сірники. Якщо K непарне, то спочатку 
    # використаємо 7 (який займає 3 сірники), а потім заповнимо решту одиницями.
    if k % 2 == 0:
        max_val = "1" * (k // 2)
    else:
        max_val = "7" + "1" * ((k - 3) // 2)

    # --- НАЙМЕНШЕ ЧИСЛО ---
    # Кількість сірників для кожної цифри:
    # 0 - 6, 1 - 2, 2 - 5, 3 - 5, 4 - 4, 5 - 5, 6 - 6, 7 - 3, 8 - 7, 9 - 6
    costs = [6, 2, 5, 5, 4, 5, 6, 3, 7, 6]
    
    # Жадібна стратегія для найменшого числа: на кожному розряді вибираємо найменшу можливу цифру,
    # яка дозволяє заповнити решту розрядів.

    # 1. Визначаємо кількість розрядів
    # Щоб число було найменшим, розрядів має бути мінімально: L = ceil(K/7)
    # ділимо на 7, бо це максимальна кількість сірників для однієї цифри (цифра 8).
    
    L = math.ceil(k / 7) # мінімальна кількість розрядів для числа, яке можна скласти з K сірників
    
    # 2. Формуємо найменше число, вибираючи цифри для кожного розряду
    # Для кожного розряду пробуємо цифри від 0 до 9, перевіряючи, чи можна вибрати цю цифру і при цьому
    # заповнити решту розрядів з залишком сірників.
    min_val = [] # список для зберігання цифр найменшого числа
    current_k = k # залишок сірників, які ще треба використати
    
    for i in range(L): # проходимо по кожному розряду
        # Пробуємо цифри від 0 до 9
        for digit in range(10):
            # Перша цифра не може бути 0
            if i == 0 and digit == 0:
                continue
                
            c = costs[digit] # кількість сірників, необхідна для поточної цифри
            rem_k = current_k - c # скільки сірників залишиться після вибору цієї цифри
            rem_len = L - 1 - i # скільки розрядів залишилося заповнити
            
            # Перевірка: чи можна заповнити решту розрядів?
            # Мінімально на розряд треба 2 сірники (цифра 1), максимально - 7 (цифра 8)
            if rem_len * 2 <= rem_k <= rem_len * 7: # якщо залишок сірників дозволяє заповнити решту розрядів, вибираємо цю цифру
                min_val.append(str(digit)) # додаємо вибрану цифру до результату
                current_k -= c # оновлюємо залишок сірників
                break
                
    print(f"{''.join(min_val)} {max_val}")

solve()