'''
https://eolymp.com/uk/problems/10309

Під час карантину через спалах COWVID-19, корови фермера Джона знайшли новий спосіб розважитися: вони почали вивчати фізику 
на вищому рівні! Вони навіть відкрили нову субатомну частинку, яку назвали "муу частинкою".

Корови проводять експеримент з n муу частинками. Кожна частинка i має "спін", який описується двома цілими числами x_i і y_i, 
що знаходяться в діапазоні від −10^9 до 10^9 включно. Іноді дві муу частинки можуть взаємодіяти. Це можливо для частинок зі 
спінами (x_i, y_i) і (x_j, y_j), якщо виконується умова x_i ≤ x_j і y_i ≤ y_j. У такому випадку одна з цих двох частинок може 
зникнути (інша залишиться без змін). У будь-який момент часу може відбутися не більше однієї взаємодії.

Вхідні дані
Перший рядок містить одне ціле число n (1≤n≤10^5) - початкову кількість муу частинок. Кожен з наступних n рядків містить 
два цілі числа, що представляють спін однієї частинки. У кожної частинки свій унікальний спін.

Вихідні дані
Виведіть одне ціле число - мінімальну кількість муу частинок, які можуть залишитися після будь-якої можливої послідовності 
взаємодій.
'''


def solve():
    # Зчитування кількості частинок
    n = int(input())
    
    particles = [] # список для збереження координат спінів частинок
    
    # Формування списку координат
    for _ in range(n):
        x, y = map(int, input().split())
        particles.append((x, y))
        
    # Сортуємо частинки за x. Це гарантує x_prev <= x_curr
    particles.sort()
    
    # Стек зберігає мінімальне значення y для кожної поточної компоненти
    # Компоненти в стеку впорядковані за x
    min_y_stack = []
    
    for _, y in particles:
        # Початкове мінімальне y для поточної частинки
        current_min_y = y
        
        # Якщо y поточної частинки більше або дорівнює мінімальному y 
        # попередньої компоненти, вони можуть взаємодіяти (оскільки x_curr >= x_prev)
        while min_y_stack and y >= min_y_stack[-1]: # доки є компоненти, які можуть взаємодіяти
            # Об'єднуємо компоненти, оскільки знайдено шлях взаємодії
            # Новим мінімумом для об'єднаної компоненти буде найменший y серед них
            top_min_y = min_y_stack.pop() # видаляємо верхню компоненту, оскільки вона зникне
            current_min_y = min(current_min_y, top_min_y)
            
        # Додаємо мінімальний y сформованої (або нової) компоненти назад у стек
        min_y_stack.append(current_min_y)
        
    # Кількість елементів у стеку дорівнює кількості компонент зв'язності
    print(len(min_y_stack))

if __name__ == "__main__":
    solve()