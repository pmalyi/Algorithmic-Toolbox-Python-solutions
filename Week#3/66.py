'''
https://eolymp.com/uk/problems/66
Асистентка в освітній установі, Анна Мартін, починає кожний робочий день зі скарги керівнику:
Джоне Сміте, ти вже купив програму для розкладу для заступника з навчальної роботи. А як щодо мене? 
Я маю складати розклад відвідувачів, як ти вимагаєш, але ти ще не забезпечив жодним програмним забезпеченням для 
адміністративного планування...

Допоможіть асистентці, організувавши розклад відвідувачів згідно з бажаними часовими інтервалами, що записані у 
зошиті асистентки.

Не дозволяється приймати двох відвідувачів одночасно. Як тільки одна зустріч закінчується, наступна може початися 
негайно — учасники можуть навіть зустрітися біля дверей кабінету.

'''

import sys

def solve():
    # Зчитуємо кількість відвідувачів
        
    n = int(input())
    meetings = []
    
    # Парсимо час та конвертуємо в хвилини
    idx = 1
    for _ in range(n):
        t1_str, t2_str = input().split()
                
        # Функція перетворення hh:mm -> int
        def to_minutes(t_str):
            h, m = map(int, t_str.split(':'))
            return h * 60 + m
        
        meetings.append((to_minutes(t1_str), to_minutes(t2_str)))

    # СОРТУВАННЯ за часом закінчення (другий елемент кортежу)
    # Це ключовий момент жадібного алгоритму
    meetings.sort(key=lambda x: x[1])

    count = 0
    last_end_time = -1  # Час, коли звільнився кабінет
    
    for start, end in meetings:
        # Якщо зустріч починається після або в момент закінчення попередньої
        if start >= last_end_time:
            count += 1
            last_end_time = end  # Оновлюємо час звільнення кабінету
            
    print(count)

if __name__ == "__main__":
    solve()